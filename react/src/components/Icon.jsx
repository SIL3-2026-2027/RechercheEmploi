// Icône standard de la maquette (classe .icon + variantes de taille)
export default function Icon({ name, size, className = '', style, stroke }) {
  const sizeClass = size ? ` icon-${size}` : ''
  return (
    <svg
      className={`icon${sizeClass}${className ? ' ' + className : ''}`}
      viewBox="0 0 24 24"
      style={style}
      stroke={stroke}
      dangerouslySetInnerHTML={{ __html: ICONS[name] }}
    />
  )
}

// SVG « nu » (sans classe .icon) : états vides, icônes de catégories…
export function RawSvg({ name, inner, strokeWidth = 1.5, ...props }) {
  return (
    <svg
      viewBox="0 0 24 24"
      fill="none"
      stroke="currentColor"
      strokeWidth={strokeWidth}
      strokeLinecap={props.strokeLinecap}
      strokeLinejoin={props.strokeLinejoin}
      className={props.className}
      dangerouslySetInnerHTML={{ __html: inner ?? ICONS[name] }}
    />
  )
}
